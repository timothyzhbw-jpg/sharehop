import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../node_modules/simple-icons/", import.meta.url));
const version = JSON.parse(readFileSync(root + "package.json", "utf8")).version;

// target id -> simple-icons slug
const MAP = {
  whatsapp: "whatsapp",
  telegram: "telegram",
  line: "line",
  messenger: "messenger",
  viber: "viber",
  kakaotalk: "kakaotalk",
  groupme: "groupme",
  discord: "discord",
  instagram: "instagram",
  snapchat: "snapchat",
  tiktok: "tiktok",
  x: "x",
  facebook: "facebook",
  reddit: "reddit",
  threads: "threads",
  bluesky: "bluesky",
  pinterest: "pinterest",
  tumblr: "tumblr",
  mastodon: "mastodon",
  hackernews: "ycombinator",
  vk: "vk",
  naver: "naver",
  hatena: "hatenabookmark",
  nextdoor: "nextdoor",
  flipboard: "flipboard",
  wechat: "wechat",
  weibo: "sinaweibo",
  qq: "qq",
  douban: "douban",
  xiaohongshu: "xiaohongshu",
  douyin: "tiktok",
  zhihu: "zhihu",
  googleclassroom: "googleclassroom",
  gmail: "gmail",
};

const lines = [];
const missing = [];
for (const [id, slug] of Object.entries(MAP)) {
  let svg;
  try {
    svg = readFileSync(`${root}icons/${slug}.svg`, "utf8");
  } catch {
    missing.push(`${id} (${slug})`);
    continue;
  }
  const d = /<path d="([^"]+)"/.exec(svg)?.[1];
  if (!d) {
    missing.push(`${id} (${slug}: no path)`);
    continue;
  }
  lines.push(`  ${JSON.stringify(id)}: ${JSON.stringify(d)},`);
}

const out = `// Generated by scripts/gen-brand-icons.mjs from simple-icons ${version} (CC0-1.0).
// Brand names and logos are trademarks of their respective owners.
// The sms and email icons are generic drawings.

const PATHS: Record<string, string> = {
${lines.join("\n")}
};

// Generic icons (not brand logos). Brands simple-icons doesn't ship
// (LinkedIn, Slack, Teams, Outlook, BAND, DingTalk) get a letter monogram
// from the widget instead of a look-alike logo.
const CUSTOM: Record<string, string> = {
  sms: '<path d="M4 5.5h16a1.5 1.5 0 0 1 1.5 1.5v9a1.5 1.5 0 0 1-1.5 1.5H10l-4.5 3.5V17.5H4A1.5 1.5 0 0 1 2.5 16V7A1.5 1.5 0 0 1 4 5.5z" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linejoin="round"/><path d="M7.5 11.5h.01M12 11.5h.01M16.5 11.5h.01" stroke="currentColor" stroke-width="2.4" stroke-linecap="round"/>',
  email:
    '<rect x="3" y="5" width="18" height="14" rx="2" fill="none" stroke="currentColor" stroke-width="1.75"/><path d="M3.5 6.5l8.5 6.5 8.5-6.5" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linejoin="round"/>',
};

/** SVG for a built-in share target, or undefined. */
export function brandIcon(id: string): string | undefined {
  const custom = CUSTOM[id];
  if (custom) return wrap(custom);
  const d = PATHS[id];
  return d ? wrap(\`<path d="\${d}" fill="currentColor"/>\`) : undefined;
}

function wrap(body: string): string {
  return \`<svg viewBox="0 0 24 24" width="24" height="24" aria-hidden="true" focusable="false">\${body}</svg>\`;
}
`;

writeFileSync(new URL("../src/element/brand-icons.ts", import.meta.url), out);
console.log(`brand-icons.ts: ${lines.length} icons from simple-icons ${version}`);
if (missing.length) console.log("missing:", missing.join(", "));
